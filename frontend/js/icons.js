// Helper to get medication form icon
function getMedFormIcon(form = 'tablet', cls = '', size = 20) {
  switch (String(form).toLowerCase()) {
    case 'capsule':
      return Icons.capsule(cls, size);
    case 'syrup':
    case 'drops':
      return Icons.droplet(cls, size);
    case 'injection':
      return Icons.syringe(cls, size);
    case 'inhaler':
      return Icons.inhaler(cls, size);
    case 'tablet':
    default:
      return Icons.pill(cls, size);
  }
}

if (typeof window !== 'undefined') {
  window.Icons = Icons;
  window.getMedFormIcon = getMedFormIcon;
}
